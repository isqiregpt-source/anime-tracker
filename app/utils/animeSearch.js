// Создаём экземпляр Fuse для нечёткого поиска
const fuse = new Fuse(russianTitlesDB, {
  keys: ['search', 'title'],
  threshold: 0.4, // Чем меньше, тем строже поиск (0 = точное совпадение, 1 = любое совпадение)
  distance: 100,
  includeScore: true,
  minMatchCharLength: 2,
});

// Функция нечёткого поиска
export const fuzzySearch = (query) => {
  if (!query || query.length < 2) return [];
  
  const results = fuse.search(query);
  return results.map(result => ({
    title: result.item.title,
    score: result.score,
  }));
};

// Функция для получения нормализованного названия
export const getNormalizedTitle = (query) => {
  const results = fuzzySearch(query);
  if (results.length > 0 && results[0].score < 0.3) {
    return results[0].title;
  }
  return null;
};